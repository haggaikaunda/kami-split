import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

// Use the image renderer pinned by the installed Next.js dependency graph.
const require = createRequire(new URL('../package.json', import.meta.url));
const sharp = require(
  require.resolve('sharp', {
    paths: [require.resolve('next/package.json')],
  }),
);
const root = new URL('../', import.meta.url);
const source = await readFile(new URL('src/app/icon.svg', root), 'utf8');
const viewBox = source.match(/viewBox="([^"]+)"/)[1];
const paths = [
  ...source.matchAll(/<path class="(sage|forest)" d="([^"]+)"\s*\/>/g),
];
if (paths.length !== 2)
  throw new Error('Expected the two canonical leaf halves');
const component = `// Generated by apps/web/scripts/generate-brand.mjs from src/app/icon.svg.\nexport function BrandMark({ className }: { className?: string }) {\n  return (\n    <svg data-ui="brand-mark" className={className} viewBox="${viewBox}" width="32" height="32" aria-hidden="true" focusable="false">\n${paths.map(([, name, d]) => `      <path fill="var(--brand-${name}, ${name === 'sage' ? '#87aa92' : '#17634d'})" d="${d}" />`).join('\n')}\n    </svg>\n  );\n}\n`;
// Installation icons have a deliberate opaque pale canvas. Expand the viewBox
// for safe platform corner masks; favicon and inline presentation stay transparent.
const rasterSource = source
  .replace(/<style>[\s\S]*?<\/style>/, '')
  .replace('viewBox="280 240 720 720"', 'viewBox="208 168 864 864"')
  .replace('class="sage"', 'fill="#87aa92"')
  .replace('class="forest"', 'fill="#17634d"');
const prettier = require('prettier');
await writeFile(
  new URL('src/components/brand-mark.tsx', root),
  await prettier.format(component, { parser: 'typescript', singleQuote: true }),
);
for (const [size, path] of [
  [180, 'src/app/apple-icon.png'],
  [192, 'public/icons/kami-grow-192.png'],
  [512, 'public/icons/kami-grow-512.png'],
]) {
  await sharp(Buffer.from(rasterSource))
    .resize(size, size)
    .flatten({ background: '#edf2ef' })
    .png()
    .toFile(fileURLToPath(new URL(path, root)));
}
